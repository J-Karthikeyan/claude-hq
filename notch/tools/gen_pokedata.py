#!/usr/bin/env python3
"""Regenerate notch/Sources/HQNotchCore/PokeData.swift from ui/app/06-trainer-packs.js,
so the notch's evolution lines / branch finals / names never drift from HQ's.

    python3 notch/tools/gen_pokedata.py          # rewrite PokeData.swift
    python3 notch/tools/gen_pokedata.py --check  # exit 1 if it is out of date
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(REPO, "ui", "app", "06-trainer-packs.js")
OUT = os.path.join(REPO, "notch", "Sources", "HQNotchCore", "PokeData.swift")


def _var(js, name):
    m = re.search(r"var %s=(.*?);\n" % re.escape(name), js, re.S)
    if not m:
        raise SystemExit("gen_pokedata: %s not found in %s" % (name, SRC))
    return m.group(1)


def parse(js):
    evo = json.loads(_var(js, "POKE_EVO"))
    real = json.loads(_var(js, "POKE_REAL"))
    names = {int(k): v for k, v in re.findall(r'(\d+):"([^"]+)"', _var(js, "DEX_NAMES"))}
    branch = {}
    for idx, body in re.findall(r"(\d+):\[(\{.*?\})\]", _var(js, "POKE_BRANCH")):
        branch[int(idx)] = [int(d) for d in re.findall(r"dex:(\d+)", body)]
    if len(evo) != 48 or len(real) != 48:
        raise SystemExit("gen_pokedata: expected 48 species, got %d/%d" % (len(evo), len(real)))
    return evo, real, names, branch


def render(evo, real, names, branch):
    def arr(xs):
        return "[" + ", ".join(str(x) for x in xs) + "]"
    lines = [
        "// GENERATED by notch/tools/gen_pokedata.py from ui/app/06-trainer-packs.js. Do not edit.",
        "// Index-aligned with HQ's 48 species (species = sha256(sessionId) % 48).",
        "",
        "public enum PokeData {",
        "    /// Evolution line (base -> final) per species index.",
        "    public static let evo: [[Int]] = [",
    ]
    lines += ["        %s," % arr(line) for line in evo]
    lines += [
        "    ]",
        "    /// Canonical species names (index-aligned).",
        "    public static let real: [String] = [",
    ]
    lines += ["        %s," % ", ".join(json.dumps(n) for n in real[i:i + 8]) for i in range(0, 48, 8)]
    lines += [
        "    ]",
        "    /// Selectable final forms per species index; element 0 is the canonical final.",
        "    public static let branch: [Int: [Int]] = [",
    ]
    lines += ["        %d: %s," % (k, arr(v)) for k, v in sorted(branch.items())]
    lines += [
        "    ]",
        "    /// Display names by National Dex number.",
        "    public static let names: [Int: String] = [",
    ]
    items = sorted(names.items())
    for i in range(0, len(items), 6):
        lines.append("        " + " ".join("%d: %s," % (k, json.dumps(v)) for k, v in items[i:i + 6]))
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main(argv):
    with open(SRC, encoding="utf-8") as f:
        text = render(*parse(f.read()))
    if "--check" in argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = ""
        if current != text:
            print("PokeData.swift is out of date: run python3 notch/tools/gen_pokedata.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
