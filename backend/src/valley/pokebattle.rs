//! The creature battle rules duel plays out. No Valley hooks of its own.
//!
//! A port of `backend/app/pokebattle.py`, which is itself "a line-for-line
//! mirror of the engine in games/pokebattle.js". Everything a battler is -- its
//! level, stats, types, move list, PP and every damage number -- is derived HERE
//! from the vendored `app/data/pokemon.json`; a client only ever sends
//! `{sp, st, br, mg, sh, name}` per creature and a move-or-switch choice, so
//! nothing on the wire can inflate a stat. [`clean_spec`] is the gate that makes
//! that true.
//!
//! Both ports draw randomness only through one `rng() -> [0, 1)` IN THE SAME
//! ORDER, which is why [`Draw`] is a closure the caller owns rather than an
//! `StdRng`: duel.rs hands it `|| cx.rng.gen()`, and the tests below hand it the
//! constant 0.5 that `backend/tests/test_valley.py`'s `FixedRng` uses, so the
//! Python test's "no crits, no misses below 50% accuracy, damage roll 93, side b
//! wins ties" carries over unchanged. See divergence 2 in `super`'s module doc
//! for why no SEEDED Python sequence is reproducible in Rust.
//!
//! Audience: none. This module never touches [`super::Out`]; it returns event
//! lists and duel.rs decides who hears them.
//!
//! The data file is read at COMPILE time with `include_str!` -- the same file
//! the Python reads -- exactly as kart.rs:75, platformer.rs:85 and fps.rs:121
//! already do with theirs, so the binary cannot start with a missing or
//! half-written catalog.

use super::{floordiv, half_up};
use serde::Deserialize;
use serde_json::{json, Map, Value};
use std::collections::HashMap;
use std::sync::LazyLock;

/// `app/data/pokemon.json`, generated by `tools/build_pokedata.mjs` from Pokemon
/// Showdown (MIT) and byte-identical to `games/pokedata.js`.
pub const DATA_JSON: &str = include_str!("../../data/pokemon.json");

// ------------------------------------------------------------------- data --
// Typed rather than a `serde_json::Value` tree, because every lookup in this
// file is by a key the Python indexes with `[]` -- a missing one is a bug, not a
// branch -- and a typed struct turns that into one panic at startup instead of
// 40 silent `unwrap_or` defaults. Unknown fields (`num`, `forme`, a move's
// `name`) are simply not read, as the Python does not read them either.

#[derive(Deserialize)]
pub struct Data {
    /// Level per stage 0..4, Python's `DATA["levels"]`.
    pub levels: Vec<i64>,
    /// One evolution line per species slot: the national dex numbers in order.
    pub lines: Vec<Vec<i64>>,
    /// species slot (as a string) -> the dex numbers a final stage may branch to.
    pub branches: HashMap<String, Vec<i64>>,
    /// dex number (as a string) -> the mega keys it may use.
    #[serde(rename = "megaFor")]
    pub mega_for: HashMap<String, Vec<String>>,
    /// dex number (as a string) -> pokemon id.
    #[serde(rename = "byDex")]
    pub by_dex: HashMap<String, String>,
    /// mega key -> pokemon id.
    pub megas: HashMap<String, String>,
    /// attacking type -> defending type -> multiplier. A missing pair is 1.
    pub chart: HashMap<String, HashMap<String, f64>>,
    pub pokemon: HashMap<String, Species>,
    pub moves: HashMap<String, Move>,
}

#[derive(Deserialize)]
pub struct Species {
    pub name: String,
    pub types: Vec<String>,
    pub bs: Base,
    /// level (as a string) -> the four move ids known at it.
    pub moves: HashMap<String, Vec<String>>,
    /// Only the alternate formes carry one; `e.get("sprite")` is None otherwise
    /// and the key still reaches the wire as null.
    #[serde(default)]
    pub sprite: Option<i64>,
}

#[derive(Deserialize)]
pub struct Base {
    pub hp: i64,
    pub atk: i64,
    pub def: i64,
    pub spa: i64,
    pub spd: i64,
    pub spe: i64,
}

#[derive(Deserialize)]
pub struct Move {
    #[serde(rename = "type")]
    pub mtype: String,
    /// "physical", "special" or "status".
    pub cat: String,
    pub bp: i64,
    /// 0 means "never misses" -- the accuracy roll is skipped entirely.
    pub acc: i64,
    pub pp: i64,
    pub pri: i64,
    #[serde(default)]
    pub sec: Option<Sec>,
    /// stat -> stages. Read in [`BOOSTS`] order, never the map's own order.
    #[serde(default)]
    pub boosts: Option<HashMap<String, i64>>,
    /// `1` means the move targets its user. Python tests `mv.get("self") == 1`.
    #[serde(rename = "self", default)]
    pub self_: Option<i64>,
    #[serde(default)]
    pub crit: Option<i64>,
    #[serde(default)]
    pub recoil: Option<[i64; 2]>,
    #[serde(default)]
    pub drain: Option<[i64; 2]>,
    #[serde(default)]
    pub heal: Option<[i64; 2]>,
    #[serde(default)]
    pub status: Option<String>,
    /// "level" for Night Shade: damage is the user's level, no crit, no roll.
    #[serde(default)]
    pub fixed: Option<String>,
    /// Struggle's recoil flag.
    #[serde(default)]
    pub struggle: Option<i64>,
}

#[derive(Deserialize)]
pub struct Sec {
    pub chance: i64,
    #[serde(default)]
    pub status: Option<String>,
    #[serde(default)]
    pub boosts: Option<HashMap<String, i64>>,
    #[serde(rename = "volatileStatus", default)]
    pub volatile_status: Option<String>,
    #[serde(rename = "self", default)]
    pub self_: Option<SecSelf>,
}

#[derive(Deserialize)]
pub struct SecSelf {
    pub boosts: HashMap<String, i64>,
}

/// Python's module-level `DATA`. Parsed once, on first use.
pub static DATA: LazyLock<Data> =
    LazyLock::new(|| serde_json::from_str(DATA_JSON).expect("app/data/pokemon.json parses"));

/// Python's `MOVES[mid]`. Panics on an id outside the catalog, as the Python's
/// `KeyError` does; every caller takes its id from the same catalog.
pub fn move_of(id: &str) -> &'static Move {
    DATA.moves.get(id).unwrap_or_else(|| panic!("no move {id} in pokemon.json"))
}

// -------------------------------------------------------------- catalogs --

/// Python's `STATS`: the five stats `calc_stat` derives beside hp.
// [`build_mon`] names the five fields of [`MonStats`] directly rather than
// looping this, so nothing outside the test that pins it reads it. Kept because
// it is the order the Python's stats dict is built in, and a reviewer comparing
// the two files looks for it. (The module-wide allow in `super` covers this
// today; the targeted one keeps the file clean when that comes off.)
#[allow(dead_code)]
pub const STATS: [&str; 5] = ["atk", "def", "spa", "spd", "spe"];

/// Python's `BOOSTS`, and the ORDER a mon's `boosts` object reaches the wire in
/// ([`view_mon`]). Also the index order of [`Mon::boosts`].
pub const BOOSTS: [&str; 7] = ["atk", "def", "spa", "spd", "spe", "accuracy", "evasion"];

/// Index into [`Mon::boosts`], or None for a stat that is not boostable. A
/// move's `boosts` map is read through [`BOOSTS`], so an unknown key there is
/// skipped exactly as Python's `if stat not in boosts: continue` skips it.
pub fn boost_i(stat: &str) -> Option<usize> {
    BOOSTS.iter().position(|s| *s == stat)
}

const B_ACCURACY: usize = 5;
const B_EVASION: usize = 6;

/// Python's `CRIT_CHANCE`. Reached only for stages 1..3; a stage of 4 or more
/// short-circuits to "always a crit" before this is asked, which is why the
/// Python can index a three-key dict without a KeyError.
pub fn crit_chance(stage: i64) -> f64 {
    match stage {
        1 => 1.0 / 24.0,
        2 => 1.0 / 8.0,
        3 => 1.0 / 2.0,
        _ => panic!("crit stage {stage} is outside CRIT_CHANCE"),
    }
}

/// Python's `STATUS_IMMUNE`: the types each status cannot be inflicted on.
/// "slp" has an empty tuple and must still be a KEY -- `set_status` indexes this
/// unconditionally.
pub const STATUS_IMMUNE: [(&str, &[&str]); 5] = [
    ("par", &["Electric"]),
    ("brn", &["Fire"]),
    ("psn", &["Poison", "Steel"]),
    ("tox", &["Poison", "Steel"]),
    ("slp", &[]),
];

fn immune_types(status: &str) -> &'static [&'static str] {
    STATUS_IMMUNE
        .iter()
        .find(|(s, _)| *s == status)
        .unwrap_or_else(|| panic!("status {status} is not in STATUS_IMMUNE"))
        .1
}

/// One `rng() -> [0, 1)` draw, in the order both ports draw them. See the
/// module doc.
pub type Draw<'a> = &'a mut dyn FnMut() -> f64;

// ------------------------------------------------------------ the battlers --

/// Python's `_int(v)`: a Python int, and never a bool. serde_json keeps the
/// distinction the JSON document makes, so `4` is an integer and `4.0` is not --
/// `test_duel_team_validation_mega_and_branch` pins `{"sp": 1, "st": 4.0}` as
/// rejected, which is the whole point of the check.
///
/// Divergence: an integer above `i64::MAX` saturates to `i64::MAX` instead of
/// staying exact. Every caller then either range-rejects it (`sp`, `to`, `i`) or
/// clamps it (`st`), which is what the Python does with the exact value too.
fn py_int(v: Option<&Value>) -> Option<i64> {
    let n = v?.as_number()?;
    if n.is_f64() {
        return None; // a float is not an int, however round it looks
    }
    n.as_i64().or(Some(i64::MAX))
}

/// One creature as a client may describe it. Python's `clean_spec` result.
#[derive(Clone, Debug, PartialEq)]
pub struct Spec {
    pub sp: usize,
    /// Already clamped to 0..=4: a stage outside it is never trusted.
    pub st: i64,
    pub br: Option<i64>,
    pub mg: Option<String>,
    pub sh: bool,
    /// The client's nickname, printable-stripped and cut to 24 characters.
    /// [`build_mon`] does not read it -- it names the battler from the data file
    /// -- and `test_duel_team_validation_mega_and_branch` pins that a 99
    /// character "name" still comes back as "Raichu". Kept because it is part of
    /// `clean_spec`'s contract with the page.
    #[allow(dead_code)] // parsed exactly as the Python parses it, and read only by its test
    pub name: String,
}

/// One move slot of a battler: its id and its remaining PP.
#[derive(Clone, Debug, PartialEq)]
pub struct Slot {
    pub id: String,
    pub pp: i64,
    pub max: i64,
}

/// The five battle stats plus hp, Python's `mon["stats"]`. Never serialised: the
/// page is told hp and max, and derives nothing itself.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct MonStats {
    pub hp: i64,
    pub atk: i64,
    pub def: i64,
    pub spa: i64,
    pub spd: i64,
    pub spe: i64,
}

impl MonStats {
    /// Python's `mon["stats"][key]`. Panics on a key outside [`STATS`] plus hp.
    pub fn get(&self, k: &str) -> i64 {
        match k {
            "hp" => self.hp,
            "atk" => self.atk,
            "def" => self.def,
            "spa" => self.spa,
            "spd" => self.spd,
            "spe" => self.spe,
            _ => panic!("no stat {k}"),
        }
    }
}

/// Everything about one battler. Python's `build_mon` dict.
#[derive(Clone, Debug, PartialEq)]
pub struct Mon {
    pub name: String,
    /// The pokemon id in `DATA["pokemon"]` -- `mon["id"]` on the wire.
    pub id: String,
    pub dex: i64,
    pub sprite: Option<i64>,
    pub mega: Option<String>,
    pub shiny: bool,
    pub sp: i64,
    pub st: i64,
    pub lvl: i64,
    pub types: Vec<String>,
    pub stats: MonStats,
    pub hp: i64,
    pub max: i64,
    /// "par", "brn", "psn", "tox" or "slp".
    pub status: Option<String>,
    /// Turns of sleep left.
    pub slp: i64,
    /// Toxic's ramp, 0..=15.
    pub tox: i64,
    pub flinch: bool,
    /// In [`BOOSTS`] order, each -6..=6.
    pub boosts: [i64; 7],
    pub moves: Vec<Slot>,
}

/// Python's `evo_pos`: where in a line a stage lands. Uses [`half_up`] and not
/// Python's `round`, because `round(0.5)` would say 0 where JS `Math.round`
/// says 1 and the two engines must agree.
pub fn evo_pos(stage: i64, length: usize) -> usize {
    let n = length as i64;
    half_up(stage as f64 / 4.0 * (n - 1) as f64).clamp(0, n - 1) as usize
}

/// Python's `eff(atk, dfn)`: the chart entry, or 1 for a pair it does not list.
pub fn eff(atk: &str, dfn: &str) -> f64 {
    DATA.chart.get(atk).and_then(|row| row.get(dfn)).copied().unwrap_or(1.0)
}

/// Python's `type_mult`: the product over the defender's types.
pub fn type_mult(move_type: &str, types: &[String]) -> f64 {
    let mut m = 1.0;
    for t in types {
        m *= eff(move_type, t);
    }
    m
}

/// Python's `calc_stat`: the main-series formula at 31 IVs and no EVs.
pub fn calc_stat(base: i64, level: i64, hp: bool) -> i64 {
    let core = floordiv((2 * base + 31) * level, 100);
    if hp {
        core + level + 10
    } else {
        core + 5
    }
}

/// Python's `clean_spec`: one creature as a client may describe it, or None for
/// anything else. The stage is CLAMPED and the species is range-checked, so no
/// value past here can index outside the data file.
pub fn clean_spec(raw: &Value) -> Option<Spec> {
    let o = raw.as_object()?; // `not isinstance(raw, dict)`
    let sp = py_int(o.get("sp"))?;
    if !(0 <= sp && (sp as usize) < DATA.lines.len()) {
        return None;
    }
    let st = py_int(o.get("st"))?;
    let st = st.clamp(0, 4); // a stage outside 0..4 is clamped, never trusted
    let br = py_int(o.get("br"));
    let mg = o.get("mg").and_then(Value::as_str).map(str::to_string);
    // Python: `raw.get("sh") is True or (_int(raw.get("sh")) and raw.get("sh") == 1)`.
    let sh = matches!(o.get("sh"), Some(Value::Bool(true))) || py_int(o.get("sh")) == Some(1);
    // Python's `raw.get("name", raw.get("n"))`: `n` is the fallback only when
    // the "name" KEY is absent, so an explicit `"name": null` does not fall
    // back. `super::clip` is `_clip`: strip unprintables, trim, then cut 24
    // CHARACTERS -- the same three steps in the same order as `clean_spec`.
    let name_v = if o.contains_key("name") { o.get("name") } else { o.get("n") };
    Some(Spec { sp: sp as usize, st, br, mg, sh, name: super::clip(name_v, 24) })
}

/// Python's `build_mon`: everything about a battler, derived from
/// (species, stage) plus the vendored data.
pub fn build_mon(spec: &Spec) -> Mon {
    let line = &DATA.lines[spec.sp];
    let pos = evo_pos(spec.st, line.len());
    let mut dex = line[pos];
    let mut mega: Option<String> = None;
    if pos == line.len() - 1 {
        // Only a final stage branches, and only a final stage at stage 4 megas.
        if let Some(opts) = DATA.branches.get(&spec.sp.to_string()) {
            if !opts.is_empty() {
                // Python: `spec.get("br") if spec.get("br") in opts else opts[0]`
                // -- a branch that is not this line's falls back to the first.
                dex = match spec.br {
                    Some(b) if opts.contains(&b) => b,
                    _ => opts[0],
                };
            }
        }
        if spec.st == 4 {
            if let Some(mg) = &spec.mg {
                let listed = DATA.mega_for.get(&dex.to_string());
                if listed.map(|v| v.contains(mg)).unwrap_or(false) {
                    mega = Some(mg.clone());
                }
            }
        }
    }
    let pid: &str = match &mega {
        Some(m) => &DATA.megas[m],
        None => &DATA.by_dex[&dex.to_string()],
    };
    let e = &DATA.pokemon[pid];
    let lvl = DATA.levels[spec.st as usize];
    let stats = MonStats {
        hp: calc_stat(e.bs.hp, lvl, true),
        atk: calc_stat(e.bs.atk, lvl, false),
        def: calc_stat(e.bs.def, lvl, false),
        spa: calc_stat(e.bs.spa, lvl, false),
        spd: calc_stat(e.bs.spd, lvl, false),
        spe: calc_stat(e.bs.spe, lvl, false),
    };
    Mon {
        name: e.name.clone(),
        id: pid.to_string(),
        dex,
        sprite: e.sprite,
        mega,
        shiny: spec.sh,
        sp: spec.sp as i64,
        st: spec.st,
        lvl,
        types: e.types.clone(),
        hp: stats.hp,
        max: stats.hp,
        stats,
        status: None,
        slp: 0,
        tox: 0,
        flinch: false,
        boosts: [0; 7],
        moves: e.moves[&lvl.to_string()]
            .iter()
            .map(|m| Slot { id: m.clone(), pp: move_of(m).pp, max: move_of(m).pp })
            .collect(),
    }
}

// ----------------------------------------------------------- the battle --

/// One side of a battle: its team and which slot is out.
#[derive(Clone, Debug, PartialEq)]
pub struct Side {
    pub team: Vec<Mon>,
    pub active: usize,
}

/// Python's battle state (`new_battle`).
#[derive(Clone, Debug, PartialEq)]
pub struct Battle {
    pub sides: [Side; 2],
    pub turn: i64,
    pub over: bool,
    /// The winning side, or None for a double knockout.
    pub winner: Option<usize>,
}

pub fn new_battle(team_a: Vec<Mon>, team_b: Vec<Mon>) -> Battle {
    Battle {
        sides: [Side { team: team_a, active: 0 }, Side { team: team_b, active: 0 }],
        turn: 1,
        over: false,
        winner: None,
    }
}

/// Python's `active(state, side)`.
pub fn active(st: &Battle, side: usize) -> &Mon {
    let s = &st.sides[side];
    &s.team[s.active]
}

/// Python's `alive(state, side)`: the slots with hp left, in team order.
pub fn alive(st: &Battle, side: usize) -> Vec<usize> {
    st.sides[side]
        .team
        .iter()
        .enumerate()
        .filter(|(_, m)| m.hp > 0)
        .map(|(i, _)| i)
        .collect()
}

/// Python's `needs_replace`: the sides whose active has fainted and who still
/// have someone to send in. Empty once the battle is over.
pub fn needs_replace(st: &Battle) -> Vec<usize> {
    if st.over {
        return Vec::new();
    }
    (0..2).filter(|&i| active(st, i).hp <= 0 && !alive(st, i).is_empty()).collect()
}

/// A normalised action. Python's `{"k": "move", "i": i}`,
/// `{"k": "switch", "to": to}` and `{"k": "struggle"}`. Never serialised.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Act {
    Move(usize),
    Switch(usize),
    Struggle,
}

/// Python's `legal`: a normalised action, or None. A side that is out of PP
/// always Struggles, and ONLY for a "move" or "struggle" key -- any other key
/// is refused.
pub fn legal(st: &Battle, side: usize, act: Option<&Value>) -> Option<Act> {
    if st.over {
        return None;
    }
    let o = act?.as_object()?; // `not isinstance(act, dict)`
    let s = &st.sides[side];
    let mon = &s.team[s.active];
    let k = o.get("k").and_then(Value::as_str);
    if k == Some("switch") {
        let to = py_int(o.get("to"))?;
        let ok = 0 <= to
            && (to as usize) < s.team.len()
            && to as usize != s.active
            && s.team[to as usize].hp > 0;
        return ok.then_some(Act::Switch(to as usize));
    }
    if mon.hp <= 0 {
        return None;
    }
    if mon.moves.iter().all(|m| m.pp <= 0) {
        return matches!(k, Some("move") | Some("struggle")).then_some(Act::Struggle);
    }
    let i = py_int(o.get("i"))?;
    let ok = k == Some("move")
        && 0 <= i
        && (i as usize) < mon.moves.len()
        && mon.moves[i as usize].pp > 0;
    ok.then_some(Act::Move(i as usize))
}

/// Python's `auto_act`: the server's pick for an absent player -- the first move
/// with PP, or Struggle.
pub fn auto_act(st: &Battle, side: usize) -> Act {
    let mon = active(st, side);
    for (i, m) in mon.moves.iter().enumerate() {
        if m.pp > 0 {
            return Act::Move(i);
        }
    }
    Act::Struggle
}

/// Python's `stage_mult_stat`: the main-series stage multiplier, as integer
/// arithmetic.
pub fn stage_mult_stat(stat: i64, s: i64) -> i64 {
    floordiv(stat * (2 + s).max(2), (2 - s).max(2))
}

/// Python's `speed`: the boosted speed, halved by paralysis.
pub fn speed(mon: &Mon) -> i64 {
    let v = stage_mult_stat(mon.stats.spe, mon.boosts[boost_i("spe").unwrap()]);
    if mon.status.as_deref() == Some("par") {
        floordiv(v, 2)
    } else {
        v
    }
}

/// Python's `damage`: (damage, type multiplier) with the main-series formula;
/// `roll` is 85..=100. The multiplier is returned even when it is 0, because the
/// caller turns that into an "immune" event rather than a 0-damage hit.
pub fn damage(att: &Mon, dfn: &Mon, mv: &Move, crit: bool, roll: i64) -> (i64, f64) {
    let mult = if mv.mtype == "???" { 1.0 } else { type_mult(&mv.mtype, &dfn.types) };
    if mult == 0.0 {
        return (0, 0.0);
    }
    if mv.fixed.as_deref() == Some("level") {
        return (att.lvl, mult);
    }
    let phys = mv.cat == "physical";
    let (a_key, d_key) = if phys { ("atk", "def") } else { ("spa", "spd") };
    let (mut a_b, mut d_b) = (att.boosts[boost_i(a_key).unwrap()], dfn.boosts[boost_i(d_key).unwrap()]);
    if crit {
        // A crit ignores the attacker's drops and the defender's boosts.
        a_b = a_b.max(0);
        d_b = d_b.min(0);
    }
    let a = stage_mult_stat(att.stats.get(a_key), a_b);
    let d = stage_mult_stat(dfn.stats.get(d_key), d_b);
    let mut base = floordiv(floordiv((floordiv(2 * att.lvl, 5) + 2) * mv.bp * a, d), 50) + 2;
    if crit {
        base = (base as f64 * 1.5).floor() as i64;
    }
    base = floordiv(base * roll, 100);
    if att.types.contains(&mv.mtype) {
        base = (base as f64 * 1.5).floor() as i64; // same-type attack bonus
    }
    base = (base as f64 * mult).floor() as i64;
    if phys && att.status.as_deref() == Some("brn") {
        base = (base as f64 * 0.5).floor() as i64;
    }
    (base.max(1), mult)
}

