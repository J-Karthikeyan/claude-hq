    #[test]
    fn the_end_of_turn_residuals_are_burn_poison_and_a_ramping_toxic() {
        // Driven through `end_of_turn` itself rather than a whole turn, so no
        // attack's damage is mixed into the hp the residual takes.
        let residual = |status: &str, tox: i64| {
            let mut st = new_battle(vec![mon(CHARIZARD)], vec![mon(VENUSAUR)]);
            st.sides[0].team[0].status = Some(status.into());
            st.sides[0].team[0].tox = tox;
            let before = st.sides[0].team[0].hp;
            let mut r = fixed();
            let ev = {
                let mut t = Turn { s: &mut st, rng: &mut r, ev: Vec::new(), moved: [true, true] };
                t.end_of_turn();
                t.ev
            };
            (before - st.sides[0].team[0].hp, ev, st.sides[0].team[0].tox)
        };
        let (lost, ev, _) = residual("brn", 0);
        assert_eq!(lost, 167 / 16);
        assert_eq!(ev[0], json!({"t": "residual", "side": 0, "name": "Charizard", "hp": 167 - 10,
                                 "max": 167, "why": "brn"}));
        assert_eq!(residual("psn", 0).0, 167 / 8);
        // Toxic ramps BEFORE it bites, so the first tick is 1/16 and the next 2/16.
        let (lost, ev, tox) = residual("tox", 0);
        assert_eq!((lost, tox), (167 / 16, 1));
        assert_eq!(ev[0]["why"], "tox");
        assert_eq!(residual("tox", 7).0, 167 * 8 / 16);
        assert_eq!(residual("tox", 15).0, 167 * 15 / 16); // the ramp caps at 15
        // A fainted creature takes no residual at all.
        let mut st = new_battle(vec![mon(CHARIZARD)], vec![mon(VENUSAUR)]);
        st.sides[0].team[0].status = Some("brn".into());
        st.sides[0].team[0].hp = 0;
        st.sides[1].team[0].flinch = true;
        let mut r = fixed();
        let ev = {
            let mut t = Turn { s: &mut st, rng: &mut r, ev: Vec::new(), moved: [true, true] };
            t.end_of_turn();
            t.ev
        };
        assert!(ev.is_empty());
        assert!(!st.sides[1].team[0].flinch); // ... but every flinch is cleared
    }

