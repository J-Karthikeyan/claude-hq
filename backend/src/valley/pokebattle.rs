/// Python's `_Turn`: one turn's mutations plus the event list they produced.
/// Every event is built with `json!` so its KEY ORDER is the Python's dict
/// order, which the page reads.
struct Turn<'a> {
    s: &'a mut Battle,
    rng: Draw<'a>,
    ev: Vec<Value>,
    /// Whether each side has already acted -- the flinch rule reads it.
    moved: [bool; 2],
}

impl Turn<'_> {
    fn mon(&self, side: usize) -> &Mon {
        active(self.s, side)
    }

    fn mon_mut(&mut self, side: usize) -> &mut Mon {
        let i = self.s.sides[side].active;
        &mut self.s.sides[side].team[i]
    }

    fn switch(&mut self, side: usize, to: usize) {
        {
            let old = self.mon_mut(side);
            old.boosts = [0; 7];
            old.flinch = false;
            if old.status.as_deref() == Some("tox") {
                old.tox = 0; // Toxic's ramp resets on a switch out
            }
        }
        self.s.sides[side].active = to;
        let name = self.mon(side).name.clone();
        self.ev.push(json!({"t": "switch", "side": side, "slot": to, "name": name}));
    }

    fn boosts(&mut self, side: usize, boosts: &HashMap<String, i64>) {
        for (bi, stat) in BOOSTS.iter().enumerate() {
            let Some(&want) = boosts.get(*stat) else { continue };
            let mon = self.mon_mut(side);
            let cur = mon.boosts[bi];
            let new = (cur + want).clamp(-6, 6);
            mon.boosts[bi] = new;
            let name = mon.name.clone();
            self.ev.push(json!({"t": "boost", "side": side, "name": name, "stat": stat,
                                "n": new - cur, "want": want}));
        }
    }

    fn set_status(&mut self, side: usize, status: &str, primary: bool) {
        let immune = immune_types(status);
        let (name, cur) = {
            let mon = self.mon(side);
            (mon.name.clone(), mon.status.clone())
        };
        let blocked = cur.is_some() || {
            let mon = self.mon(side);
            mon.types.iter().any(|t| immune.contains(&t.as_str()))
        };
        if blocked {
            // Only a PRIMARY status move says so; a secondary effect fails quietly.
            if primary {
                let why = if cur.is_some() { "already" } else { "immune" };
                self.ev.push(json!({"t": "fail", "side": side, "name": name, "why": why,
                                    "s": cur}));
            }
            return;
        }
        // The sleep length is the only draw in here, and it happens after the
        // immunity check, exactly as the Python's does.
        let slp = (status == "slp").then(|| 1 + ((self.rng)() * 3.0).floor() as i64);
        let mon = self.mon_mut(side);
        mon.status = Some(status.to_string());
        if let Some(n) = slp {
            mon.slp = n;
        }
        if status == "tox" {
            mon.tox = 0;
        }
        self.ev.push(json!({"t": "status", "side": side, "name": name, "s": status}));
    }

    fn heal(&mut self, side: usize, amount: i64, why: &str) {
        let (name, hp, max) = {
            let mon = self.mon_mut(side);
            mon.hp = (mon.hp + amount).min(mon.max);
            (mon.name.clone(), mon.hp, mon.max)
        };
        self.ev.push(json!({"t": "heal", "side": side, "name": name, "hp": hp, "max": max,
                            "why": why}));
    }

    fn hurt(&mut self, side: usize, amount: i64, why: &str) {
        let (name, hp, max) = {
            let mon = self.mon_mut(side);
            mon.hp = (mon.hp - amount).max(0);
            (mon.name.clone(), mon.hp, mon.max)
        };
        self.ev.push(json!({"t": "residual", "side": side, "name": name, "hp": hp, "max": max,
                            "why": why}));
        if hp <= 0 {
            self.ev.push(json!({"t": "faint", "side": side, "name": name}));
        }
    }

    fn cant(&mut self, side: usize, why: &str) {
        let name = self.mon(side).name.clone();
        self.ev.push(json!({"t": "cant", "side": side, "name": name, "why": why}));
    }

    fn use_move(&mut self, side: usize, act: Act) {
        let foe = 1 - side;
        if self.mon(side).hp <= 0 {
            return;
        }
        if self.mon(side).status.as_deref() == Some("slp") {
            if self.mon(side).slp > 0 {
                self.mon_mut(side).slp -= 1;
                self.cant(side, "slp");
                return;
            }
            self.mon_mut(side).status = None;
            let name = self.mon(side).name.clone();
            self.ev.push(json!({"t": "cure", "side": side, "name": name, "s": "slp"}));
        }
        if self.mon(side).flinch {
            self.cant(side, "flinch");
            return;
        }
        if self.mon(side).status.as_deref() == Some("par") && (self.rng)() < 0.25 {
            self.cant(side, "par");
            return;
        }
        // PP comes off here, before anything can miss or fail.
        let mid = match act {
            Act::Struggle => "struggle".to_string(),
            Act::Move(i) => {
                let mon = self.mon_mut(side);
                mon.moves[i].pp -= 1;
                mon.moves[i].id.clone()
            }
            Act::Switch(_) => panic!("use_move with a switch"),
        };
        let mv = move_of(&mid);
        let user = self.mon(side).name.clone();
        self.ev.push(json!({"t": "move", "side": side, "name": user, "move": mid}));
        let target_self = mv.self_ == Some(1);
        if !target_self && self.mon(foe).hp <= 0 {
            self.ev.push(json!({"t": "fail", "side": side, "name": user, "why": "notarget"}));
            return;
        }
        if !target_self && mv.acc > 0 {
            let s = (self.mon(side).boosts[B_ACCURACY] - self.mon(foe).boosts[B_EVASION])
                .clamp(-6, 6);
            let (num, den) = if s >= 0 { (3 + s, 3) } else { (3, 3 - s) };
            // Python's `if not self.rng() * 100 < mv["acc"] * num / den` -- a
            // TRUE float division, not an integer one. Written as `>=` rather
            // than the Python's negated `<` because clippy rejects `!(a < b)`
            // on a partial order; both sides here are finite (the draw is in
            // [0, 1) and acc/num/den are small positive integers), so the two
            // spellings cannot disagree.
            if (self.rng)() * 100.0 >= mv.acc as f64 * num as f64 / den as f64 {
                // The Python credits the miss to the FOE's side with the USER's
                // name; the page reads it as "whose attack missed".
                self.ev.push(json!({"t": "miss", "side": foe, "name": user}));
                return;
            }
        }
        if mv.cat == "status" {
            // heal, then boosts, then status: one branch only, as the Python's
            // if/elif chain does.
            if let Some(h) = mv.heal {
                if self.mon(side).hp >= self.mon(side).max {
                    self.ev
                        .push(json!({"t": "fail", "side": side, "name": user, "why": "fullhp"}));
                } else {
                    let max = self.mon(side).max;
                    let amount = half_up(max as f64 * h[0] as f64 / h[1] as f64);
                    self.heal(side, amount, "move");
                }
            } else if let Some(b) = &mv.boosts {
                self.boosts(if target_self { side } else { foe }, b);
            } else if let Some(s) = &mv.status {
                self.set_status(foe, s, true);
            }
            return;
        }
        let crit_stage = mv.crit.unwrap_or(1);
        let fixed_level = mv.fixed.as_deref() == Some("level");
        // Short-circuit order is load-bearing: a fixed-damage move draws
        // NEITHER the crit nor the roll, so the stream stays in step.
        let crit = !fixed_level && (crit_stage >= 4 || (self.rng)() < crit_chance(crit_stage));
        let roll = if fixed_level { 100 } else { 85 + ((self.rng)() * 16.0).floor() as i64 };
        let (dmg, mult) = damage(self.mon(side), self.mon(foe), mv, crit, roll);
        if mult == 0.0 {
            let name = self.mon(foe).name.clone();
            self.ev.push(json!({"t": "immune", "side": foe, "name": name}));
            return;
        }
        let dealt = dmg.min(self.mon(foe).hp);
        let (tname, thp, tmax) = {
            let tgt = self.mon_mut(foe);
            tgt.hp -= dealt;
            (tgt.name.clone(), tgt.hp, tgt.max)
        };
        self.ev.push(json!({"t": "dmg", "side": foe, "name": tname, "hp": thp, "max": tmax,
                            "eff": mult, "crit": crit, "move": mid}));
        if thp <= 0 {
            self.ev.push(json!({"t": "faint", "side": foe, "name": tname}));
        }
        if let Some(d) = mv.drain {
            if self.mon(side).hp < self.mon(side).max {
                let amount = half_up(dealt as f64 * d[0] as f64 / d[1] as f64).max(1);
                self.heal(side, amount, "drain");
            }
        }
        if let Some(sec) = &mv.sec {
            if (self.rng)() * 100.0 < sec.chance as f64 {
                if self.mon(foe).hp > 0 {
                    if let Some(s) = &sec.status {
                        self.set_status(foe, s, false);
                    }
                    if let Some(b) = &sec.boosts {
                        self.boosts(foe, b);
                    }
                    // A flinch only lands on someone who has not moved yet.
                    if sec.volatile_status.as_deref() == Some("flinch") && !self.moved[foe] {
                        self.mon_mut(foe).flinch = true;
                    }
                }
                if let Some(sf) = &sec.self_ {
                    self.boosts(side, &sf.boosts);
                }
            }
        }
        if mv.struggle.is_some() {
            let max = self.mon(side).max;
            self.hurt(side, half_up(max as f64 / 4.0).max(1), "recoil");
        } else if let Some(r) = mv.recoil {
            let amount = half_up(dealt as f64 * r[0] as f64 / r[1] as f64).max(1);
            self.hurt(side, amount, "recoil");
        }
    }

    /// Python's `order`: switches first, then priority, then speed, with a coin
    /// toss on an exact tie.
    fn order(&mut self, acts: &[Act; 2]) -> [usize; 2] {
        let (k0, k1) = {
            let key = |side: usize| -> (i64, i64, i64) {
                let mon = self.mon(side);
                match acts[side] {
                    Act::Switch(_) => (1, 0, speed(mon)),
                    Act::Struggle => (0, move_of("struggle").pri, speed(mon)),
                    Act::Move(i) => (0, move_of(&mon.moves[i].id).pri, speed(mon)),
                }
            };
            (key(0), key(1))
        };
        if k0 == k1 {
            // Python's `[0, 1] if self.rng() < 0.5 else [1, 0]`: side b wins the
            // tie on the 0.5 the test fixture always draws.
            return if (self.rng)() < 0.5 { [0, 1] } else { [1, 0] };
        }
        if k0 > k1 {
            [0, 1]
        } else {
            [1, 0]
        }
    }

    fn end_of_turn(&mut self) {
        for side in 0..2 {
            let (hp, max, status) = {
                let mon = self.mon(side);
                (mon.hp, mon.max, mon.status.clone())
            };
            if hp <= 0 {
                continue;
            }
            match status.as_deref() {
                Some("brn") => self.hurt(side, floordiv(max, 16).max(1), "brn"),
                Some("psn") => self.hurt(side, floordiv(max, 8).max(1), "psn"),
                Some("tox") => {
                    let tox = {
                        let mon = self.mon_mut(side);
                        mon.tox = (mon.tox + 1).min(15);
                        mon.tox
                    };
                    self.hurt(side, floordiv(max * tox, 16).max(1), "tox");
                }
                _ => {}
            }
        }
        for side in 0..2 {
            self.mon_mut(side).flinch = false;
        }
    }
}

/// Python's `_finish`: a side with nobody left ends the battle, and a double
/// knockout has no winner.
fn finish(st: &mut Battle, ev: &mut Vec<Value>) {
    let (a, b) = (!alive(st, 0).is_empty(), !alive(st, 1).is_empty());
    if !(a && b) {
        st.over = true;
        st.winner = if a {
            Some(0)
        } else if b {
            Some(1)
        } else {
            None
        };
        ev.push(json!({"t": "end", "winner": st.winner}));
    }
}

/// Python's `resolve_turn`: both sides' already-legal actions -> ordered events;
/// mutates `st`.
pub fn resolve_turn(st: &mut Battle, act_a: Act, act_b: Act, rng: Draw) -> Vec<Value> {
    let acts = [act_a, act_b];
    let mut ev = {
        let mut t = Turn { s: st, rng, ev: Vec::new(), moved: [false, false] };
        for side in t.order(&acts) {
            match acts[side] {
                Act::Switch(to) => t.switch(side, to),
                other => t.use_move(side, other),
            }
            t.moved[side] = true;
        }
        t.end_of_turn();
        t.ev
    };
    st.turn += 1;
    finish(st, &mut ev);
    ev
}

/// Python's `replace`: a side whose active fainted sends in `slot` (which must
/// be alive). The `_Turn` is built with a generator that always returns 0.0,
/// because a switch draws nothing.
pub fn replace(st: &mut Battle, side: usize, slot: usize) -> Vec<Value> {
    let mut never = || 0.0;
    let mut t = Turn { s: st, rng: &mut never, ev: Vec::new(), moved: [false, false] };
    t.switch(side, slot);
    t.ev
}

/// Python's `view_mon`: the fourteen keys the page is told about one battler,
/// IN THIS ORDER, plus its move slots. Note `stats` is NOT among them -- the
/// page is given hp and max and derives nothing.
pub fn view_mon(m: &Mon) -> Value {
    let mut boosts = Map::new();
    for (i, k) in BOOSTS.iter().enumerate() {
        boosts.insert((*k).to_string(), json!(m.boosts[i]));
    }
    json!({
        "name": m.name, "id": m.id, "dex": m.dex, "sprite": m.sprite, "mega": m.mega,
        "shiny": m.shiny, "sp": m.sp, "st": m.st, "lvl": m.lvl, "types": m.types,
        "hp": m.hp, "max": m.max, "status": m.status, "boosts": Value::Object(boosts),
        "moves": m.moves.iter()
            .map(|s| json!({"id": s.id, "pp": s.pp, "max": s.max}))
            .collect::<Vec<_>>(),
    })
}

