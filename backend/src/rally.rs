/// To 0.1 m, never -0.0 (so "-0.0" and "0" give the same content key).
fn r1(v: f64) -> f64 {
    (v * 10.0).round() / 10.0 + 0.0
}

fn num(v: Option<&Value>) -> Option<f64> {
    let f = v?.as_number()?.as_f64()?;
    f.is_finite().then_some(f)
}

/// One gate, canonical.
#[derive(Clone, Debug, PartialEq)]
pub struct Gate {
    pub x: f64,
    pub z: f64,
    /// Heading in whole degrees, 0..360.
    pub h: i64,
    pub w: f64,
}

impl Gate {
    /// The driving direction through the gate (0 = north = -z, 90 = east).
    pub fn dir(&self) -> (f64, f64) {
        let a = (self.h as f64).to_radians();
        (a.sin(), -a.cos())
    }

    /// Signed distance of (x, z) past the gate line, along its heading.
    pub fn side(&self, x: f64, z: f64) -> f64 {
        let (dx, dz) = self.dir();
        (x - self.x) * dx + (z - self.z) * dz
    }

    /// Does moving from a to b cross this gate forward, inside its half-width?
    /// Some(fraction of the way from a to b) when it does.
    pub fn crossed(&self, a: (f64, f64), b: (f64, f64)) -> Option<f64> {
        let (sa, sb) = (self.side(a.0, a.1), self.side(b.0, b.1));
        if !(sa < 0.0 && sb >= 0.0) {
            return None;
        }
        let f = sa / (sa - sb); // 0..=1
        let (ix, iz) = (a.0 + (b.0 - a.0) * f, a.1 + (b.1 - a.1) * f);
        let (dx, dz) = self.dir();
        let lat = (ix - self.x) * -dz + (iz - self.z) * dx; // along the gate line
        (lat.abs() <= self.w).then_some(f)
    }
}

/// A playable stage: canonical data, its key and what the referee needs.
#[derive(Clone, Debug)]
pub struct Stage {
    /// "c-" + 12 hex: the race key, results key and board.
    pub key: String,
    pub name: String,
    /// The canonical `data`.
    pub data: Value,
    pub road: Vec<(f64, f64, f64)>,
    pub gates: Vec<Gate>,
}

impl Stage {
    /// The canonical MapDoc, as sent to clients.
    pub fn doc(&self) -> Value {
        json!({"kind": GAME, "v": 1, "name": self.name, "data": self.data})
    }

    /// Where a car stands before its first frame (and is fixed back to): the
    /// road's first point, facing the second.
    pub fn start(&self) -> (f64, f64, f64, i64) {
        let (x0, z0, y0) = self.road[0];
        let (x1, z1, _) = self.road[1];
        let yaw = (x1 - x0).atan2(-(z1 - z0)).to_degrees().rem_euclid(360.0).round() as i64 % 360;
        (x0, z0, y0, yaw)
    }
}

/// Earliest point on the road polyline within GATE_NEAR of (x, z) that lies
/// strictly further along than `after`: its distance along the road (2D).
fn along_road(road: &[(f64, f64, f64)], x: f64, z: f64, after: f64) -> Option<f64> {
    let mut cum = 0.0;
    for w in road.windows(2) {
        let ((ax, az, _), (bx, bz, _)) = (w[0], w[1]);
        let (vx, vz) = (bx - ax, bz - az);
        let l2 = vx * vx + vz * vz;
        let l = l2.sqrt();
        let t = if l2 > 0.0 { (((x - ax) * vx + (z - az) * vz) / l2).clamp(0.0, 1.0) } else { 0.0 };
        let (px, pz) = (ax + vx * t, az + vz * t);
        let s = cum + t * l;
        if (x - px).hypot(z - pz) <= GATE_NEAR && s > after {
            return Some(s);
        }
        cum += l;
    }
    None
}

/// A stage name: trimmed, 1-40 printable characters, no markup, no links (the
/// gallery's rules, at the rally length).
fn doc_name(v: Option<&Value>) -> Result<String, String> {
    let s = v.and_then(Value::as_str).ok_or("the stage needs a name")?;
    crate::maps::clean_name_max(s, MAX_NAME)
}

/// Check a rally MapDoc's `data` and return it CANONICAL: keys in the order
/// seed, biome, night, length, road, gates; road points [x, z, y] and gate x, z,
/// w rounded to 0.1 m, length and gate headings to whole numbers (headings into
/// 0..359), every other key dropped. Never panics; the error is plain words.
pub fn validate_custom(data: &Value) -> Result<Value, String> {
    let obj = data.as_object().ok_or("the stage data must be an object")?;
    let size = serde_json::to_string(data).map(|s| s.len()).unwrap_or(usize::MAX);
    if size > MAX_RAW_BYTES {
        return Err("the stage data is too big".into());
    }
    let seed = obj.get("seed").and_then(Value::as_str).ok_or("seed must be a string")?;
    if seed.chars().count() > MAX_SEED || seed.chars().any(char::is_control) {
        return Err(format!("seed must be at most {MAX_SEED} printable characters"));
    }
    let biome = obj
        .get("biome")
        .and_then(Value::as_str)
        .filter(|b| BIOMES.contains(b))
        .ok_or("biome must be forest, hills or snow")?;
    let night = obj.get("night").and_then(Value::as_bool).ok_or("night must be true or false")?;
    let length = num(obj.get("length"))
        .map(f64::round)
        .filter(|l| (MIN_LENGTH..=MAX_LENGTH).contains(l))
        .ok_or("length must be 1000 to 6000 metres")?;

    let raw_road = obj.get("road").and_then(Value::as_array).ok_or("road must be a list of [x, z, y] points")?;
    if !(MIN_POINTS..=MAX_POINTS).contains(&raw_road.len()) {
        return Err(format!("a road has {MIN_POINTS} to {MAX_POINTS} points, this one has {}", raw_road.len()));
    }
    let mut road = Vec::with_capacity(raw_road.len());
    for (i, p) in raw_road.iter().enumerate() {
        let a = p.as_array().filter(|a| a.len() == 3).ok_or_else(|| format!("road point {i} must be [x, z, y]"))?;
        let mut c = [0.0; 3];
        for k in 0..3 {
            let v = num(a.get(k)).map(r1).ok_or_else(|| format!("road point {i} must be [x, z, y] numbers"))?;
            if v.abs() > MAX_COORD {
                return Err(format!("road point {i} is more than {MAX_COORD} m out"));
            }
            c[k] = v;
        }
        road.push((c[0], c[1], c[2]));
    }
    for (i, w) in road.windows(2).enumerate() {
        let d = (w[1].0 - w[0].0).hypot(w[1].1 - w[0].1);
        if !(MIN_GAP..=MAX_GAP).contains(&d) {
            return Err(format!("road points {i} and {} are {d:.1} m apart (2 to 30 m)", i + 1));
        }
    }

    let raw_gates = obj.get("gates").and_then(Value::as_array).ok_or("gates must be a list")?;
    if !(MIN_GATES..=MAX_GATES).contains(&raw_gates.len()) {
        return Err(format!("a stage has {MIN_GATES} to {MAX_GATES} gates, this one has {}", raw_gates.len()));
    }
    let mut gates = Vec::with_capacity(raw_gates.len());
    let mut after = -1.0;
    for (i, g) in raw_gates.iter().enumerate() {
        let g = g.as_object().ok_or_else(|| format!("gate {i} must be an object"))?;
        let coord = |k: &str| -> Result<f64, String> {
            let v = num(g.get(k)).map(r1).ok_or_else(|| format!("gate {i} needs a number {k}"))?;
            if v.abs() > MAX_COORD {
                return Err(format!("gate {i} is more than {MAX_COORD} m out"));
            }
            Ok(v)
        };
        let (x, z) = (coord("x")?, coord("z")?);
        let h = num(g.get("h")).ok_or_else(|| format!("gate {i} needs a heading h"))?;
        let h = (h.round() as i64).rem_euclid(360);
        let w = num(g.get("w"))
            .map(r1)
            .filter(|w| (MIN_HALF..=MAX_HALF).contains(w))
            .ok_or_else(|| format!("gate {i} half-width w must be 4 to 20 m"))?;
        after = along_road(&road, x, z, after).ok_or_else(|| {
            format!("gate {i} is not within {GATE_NEAR} m of the road after gate {}", i.max(1) - 1)
        })?;
        gates.push(Gate { x, z, h, w });
    }

    let road_v: Vec<Value> = road.iter().map(|(x, z, y)| json!([x, z, y])).collect();
    let gates_v: Vec<Value> = gates.iter().map(|g| json!({"x": g.x, "z": g.z, "h": g.h, "w": g.w})).collect();
    let mut out = Map::new();
    out.insert("seed".into(), json!(seed));
    out.insert("biome".into(), json!(biome));
    out.insert("night".into(), json!(night));
    out.insert("length".into(), json!(length as i64));
    out.insert("road".into(), Value::Array(road_v));
    out.insert("gates".into(), Value::Array(gates_v));
    let out = Value::Object(out);
    if serde_json::to_string(&out).map(|s| s.len()).unwrap_or(usize::MAX) > MAX_BYTES {
        return Err("the stage data is too big (12 KiB at most once rounded)".into());
    }
    Ok(out)
}

/// A whole MapDoc `{"kind":"rally","v":1,"name","data"}` to a playable stage.
pub fn stage_from_doc(doc: &Value) -> Result<Stage, String> {
    let d = doc.as_object().ok_or("send the stage as a map document")?;
    if d.get("kind").and_then(Value::as_str) != Some(GAME) {
        return Err("this is not a rally stage".into());
    }
    if d.get("v").and_then(Value::as_i64) != Some(1) {
        return Err("this stage was made by a newer editor".into());
    }
    let name = doc_name(d.get("name"))?;
    let data = validate_custom(d.get("data").unwrap_or(&Value::Null))?;
    let road = data["road"]
        .as_array()
        .map(|a| {
            a.iter()
                .map(|p| (p[0].as_f64().unwrap_or(0.0), p[1].as_f64().unwrap_or(0.0), p[2].as_f64().unwrap_or(0.0)))
                .collect()
        })
        .unwrap_or_default();
    let gates = data["gates"]
        .as_array()
        .map(|a| {
            a.iter()
                .map(|g| Gate {
                    x: g["x"].as_f64().unwrap_or(0.0),
                    z: g["z"].as_f64().unwrap_or(0.0),
                    h: g["h"].as_i64().unwrap_or(0),
                    w: g["w"].as_f64().unwrap_or(0.0),
                })
                .collect()
        })
        .unwrap_or_default();
    let key = crate::mapkey::content_key(GAME, &data);
    Ok(Stage { key, name, data, road, gates })
}

/// Python truthiness of a JSON value (the `dr` flag).
fn truthy(v: Option<&Value>) -> bool {
    match v {
        None | Some(Value::Null) => false,
        Some(Value::Bool(b)) => *b,
        Some(Value::Number(n)) => n.as_f64().map(|f| f != 0.0).unwrap_or(true),
        Some(Value::String(s)) => !s.is_empty(),
        Some(Value::Array(a)) => !a.is_empty(),
        Some(Value::Object(o)) => !o.is_empty(),
    }
}

/// Someone's name for the results: display name, else handle.
fn name_of(user: &Value) -> String {
    let d = user.get("displayName").and_then(Value::as_str).unwrap_or("");
    if !d.is_empty() {
        return d.to_string();
    }
    user.get("handle").and_then(Value::as_str).unwrap_or("").to_string()
}

// ------------------------------------------------------------------ the race --
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Phase {
    Idle,
    Countdown,
    Racing,
    Done,
}

impl Phase {
    pub fn as_str(self) -> &'static str {
        match self {
            Phase::Idle => "idle",
            Phase::Countdown => "countdown",
            Phase::Racing => "racing",
            Phase::Done => "done",
        }
    }
}

#[derive(Clone, Debug)]
pub struct Player {
    pub user: Value,
    pub car: i64,
    /// Last accepted position, metres.
    pub x: f64,
    pub z: f64,
    pub y: f64,
    pub yaw: i64,
    pub v: i64,
    pub dr: bool,
    /// Has a first frame been taken (the car is placed)?
    pub anchored: bool,
    /// The sender's clock (centiseconds) on the last frame taken, and on the first.
    pub q: Option<i64>,
    pub q0: i64,
    pub t0: f64,
    /// Server time of the last accepted frame.
    pub at: f64,
    /// The next gate to cross.
    pub next: usize,
    /// Split times (ms from go) of every gate crossed, last gate included.
    pub splits: Vec<i64>,
    pub fin: Option<i64>,
    /// Why they did not finish: "left", "disconnect" or "timeout".
    pub dnf: Option<&'static str>,
    pub away: Option<f64>,
    /// (tokens, last refill)
    pub bucket: (f64, f64),
    pub fix_at: f64,
    pub bad: u32,
}

impl Player {
    fn racing(&self) -> bool {
        self.fin.is_none() && self.dnf.is_none()
    }

    fn fix(&self, uid: &str) -> Value {
        json!({"uid": uid, "x": (self.x * 100.0).round() as i64, "z": (self.z * 100.0).round() as i64,
               "y": (self.y * 100.0).round() as i64, "yaw": self.yaw})
    }
}

/// A multi-stage event's running totals in this room.
#[derive(Clone, Debug, Default)]
pub struct Event {
    pub count: i64,
    /// The index of the stage being run (or last run).
    pub index: i64,
    /// The last index whose stage reached "done".
    pub completed: Option<i64>,
    /// uid -> (summed ms, stages finished in a row from index 0).
    pub totals: BTreeMap<String, (i64, i64)>,
}

/// One room's rally: idle -> countdown -> racing -> done; the host starts the next.
#[derive(Debug)]
pub struct Rally {
    pub stage: Option<Arc<Stage>>, // shared, so a position frame never copies the road
    pub phase: Phase,
    pub go_at: f64,
    pub players: Vec<(String, Player)>, // in grid order
    pub cars: BTreeMap<String, i64>,    // user_id -> car, kept between stages
    pub event: Option<Event>,
    /// The last stage's `done` payload, for a socket that (re)joins after it.
    pub results: Option<Value>,
    pub dirty: Vec<String>,
}

impl Default for Rally {
    fn default() -> Self {
        Self::new()
    }
}

/// The ms of server time t on the stage clock.
fn ms_since(go_at: f64, t: f64) -> i64 {
    ((t - go_at) * 1000.0).round().max(0.0) as i64
}

/// Server ms on the wire (`go.at`, `snap.t`).
pub fn wire_ms(t: f64) -> i64 {
    (t * 1000.0).round() as i64
}

impl Rally {
    pub fn new() -> Self {
        Self {
            stage: None,
            phase: Phase::Idle,
            go_at: 0.0,
            players: Vec::new(),
            cars: BTreeMap::new(),
            event: None,
            results: None,
            dirty: Vec::new(),
        }
    }

    pub fn player(&self, uid: &str) -> Option<&Player> {
        self.players.iter().find(|(u, _)| u == uid).map(|(_, p)| p)
    }

    fn player_mut(&mut self, uid: &str) -> Option<&mut Player> {
        self.players.iter_mut().find(|(u, _)| u == uid).map(|(_, p)| p)
    }

    pub fn running(&self) -> bool {
        matches!(self.phase, Phase::Countdown | Phase::Racing)
    }

    fn event_count(&self) -> i64 {
        self.event.as_ref().map(|e| e.count).unwrap_or(1)
    }

    /// The `rally` event: the stage everyone races.
    pub fn rally_ev(&self) -> Option<Value> {
        let s = self.stage.as_ref()?;
        let mut v = json!({"key": s.key, "name": s.name, "gates": s.gates.len(), "stage": s.doc()});
        if let Some(e) = &self.event {
            v["event"] = json!({"index": e.index, "count": e.count});
        }
        Some(v)
    }

    pub fn go_ev(&self) -> Value {
        json!({"at": wire_ms(self.go_at), "countdown": COUNTDOWN as i64})
    }

    /// The deadline: max(MIN_STAGE, LEADER_X x the leader's time) after go.
    pub fn deadline(&self) -> f64 {
        let lead = self.players.iter().filter_map(|(_, p)| p.fin).min();
        let secs = lead.map(|ms| LEADER_X * ms as f64 / 1000.0).unwrap_or(0.0);
        self.go_at + MIN_STAGE.max(secs)
    }

    pub fn car(&mut self, uid: &str, msg: &Value) -> Option<i64> {
        let c = as_num(msg.get("car"), -1.0, CARS as f64)?;
        if c != c.trunc() || !(0.0..CARS as f64).contains(&c) {
            return None;
        }
        let c = c as i64;
        self.cars.insert(uid.to_string(), c);
        let running = self.phase == Phase::Racing;
        if let Some(p) = self.player_mut(uid) {
            if !running {
                p.car = c;
            }
        }
        Some(c)
    }

    /// Start a stage. `members`: the lobby in join order (the first 8 race).
    /// Returns an error for the host, or None.
    pub fn start(&mut self, members: &[(String, Value)], doc: &Value, event: Option<&Value>, t: f64)
        -> Option<String>
    {
        if self.running() {
            return Some("a stage is already running: the host can end it first".into());
        }
        let ev = match event.filter(|e| !e.is_null()) {
            None => None,
            Some(e) => {
                let idx = e.get("index").and_then(Value::as_i64);
                let cnt = e.get("count").and_then(Value::as_i64);
                match (idx, cnt) {
                    (Some(i), Some(c)) if (1..=MAX_EVENT).contains(&c) && (0..c).contains(&i) => Some((i, c)),
                    _ => return Some("bad event: index 0-4 below count 1-5".into()),
                }
            }
        };
        let stage = match stage_from_doc(doc) {
            Ok(s) => s,
            Err(e) => return Some(format!("bad stage: {e}")),
        };
        self.event = match ev {
            None | Some((_, 1)) => None,
            Some((index, count)) => {
                let carry = self.event.take().filter(|e| {
                    index > 0 && e.count == count && e.completed == Some(index - 1)
                });
                let mut e = carry.unwrap_or_default();
                e.count = count;
                e.index = index;
                if index == 0 {
                    e.totals.clear();
                }
                Some(e)
            }
        };
        let (sx, sz, sy, syaw) = stage.start();
        self.stage = Some(Arc::new(stage));
        self.phase = Phase::Countdown;
        self.go_at = t + COUNTDOWN;
        self.results = None;
        self.players = members
            .iter()
            .take(MAX_PLAYERS)
            .enumerate()
            .map(|(k, (uid, pubv))| {
                (uid.clone(), Player {
                    user: pubv.clone(),
                    car: self.cars.get(uid).copied().unwrap_or(k as i64 % CARS),
                    x: sx,
                    z: sz,
                    y: sy,
                    yaw: syaw,
                    v: 0,
                    dr: false,
                    anchored: false,
                    q: None,
                    q0: 0,
                    t0: t,
                    at: t,
                    next: 0,
                    splits: Vec::new(),
                    fin: None,
                    dnf: None,
                    away: None,
                    bucket: (POS_BURST, t),
                    fix_at: 0.0,
                    bad: 0,
                })
            })
            .collect();
        self.dirty = Vec::new();
        None
    }

    pub fn end(&mut self) {
        self.phase = Phase::Idle;
        self.players = Vec::new();
        self.results = None;
        self.dirty = Vec::new();
    }

    fn mark_dirty(&mut self, uid: &str) {
        if !self.dirty.iter().any(|u| u == uid) {
            self.dirty.push(uid.to_string());
        }
    }

    /// A position frame. Returns the correction for the sender (if any) and the
    /// events for the lobby (split / finish), in order. Before the green light,
    /// after you finish and from someone not racing, frames are ignored.
    pub fn pos(&mut self, uid: &str, msg: &Value, t: f64) -> (Option<Value>, Vec<(&'static str, Value)>) {
        let mut evs = Vec::new();
        if self.phase != Phase::Racing {
            return (None, evs);
        }
        let Some(stage) = self.stage.clone() else { return (None, evs) };
        let go_at = self.go_at;
        let Some(p) = self.player_mut(uid) else { return (None, evs) };
        if !p.racing() || p.away.is_some() {
            return (None, evs);
        }
        p.bucket.0 = POS_BURST.min(p.bucket.0 + (t - p.bucket.1) * POS_RATE);
        p.bucket.1 = t;
        if p.bucket.0 < 1.0 {
            return (None, evs);
        }
        p.bucket.0 -= 1.0;
        let x = as_num(msg.get("x"), -1e9, 1e9);
        let z = as_num(msg.get("z"), -1e9, 1e9);
        let yaw = as_num(msg.get("yaw"), -1e6, 1e6);
        let (Some(x), Some(z), Some(yaw)) = (x, z, yaw) else { return (None, evs) };
        let y = as_num(msg.get("y"), -1e9, 1e9).map(|y| y / 100.0).unwrap_or(p.y);
        let v = as_num(msg.get("v"), -10000.0, 10000.0).map(|v| v as i64).unwrap_or(0);
        let q = as_num(msg.get("q"), 0.0, ((1i64 << 30) - 1) as f64).map(|q| q as i64);
        // Elapsed time by the sender's own clock (q), as kart: an older frame
        // than the last one taken is stale, and the clock may never get more
        // than CLOCK_LEAD ahead of ours since its first frame.
        let dt = match (q, p.q) {
            (Some(q), Some(pq)) => {
                if q <= pq {
                    return (None, evs);
                }
                if (q - p.q0) as f64 / 100.0 > (t - p.t0) + CLOCK_LEAD {
                    -1.0
                } else {
                    (q - pq) as f64 / 100.0
                }
            }
            _ => (t - p.at).max(0.0),
        };
        let (xm, zm) = (x / 100.0, z / 100.0);
        let in_world = xm.abs() <= WORLD && zm.abs() <= WORLD && y.abs() <= WORLD;
        let ok = in_world
            && if p.anchored {
                let moved = (xm - p.x).hypot(zm - p.z);
                dt >= 0.0 && moved <= MAX_SPEED * dt + SLACK && moved <= MAX_STEP
            } else {
                let (sx, sz, _, _) = stage.start();
                (xm - sx).hypot(zm - sz) <= START_RADIUS
            };
        if !ok {
            p.bad += 1;
            if t - p.fix_at < FIX_GAP {
                return (None, evs);
            }
            p.fix_at = t;
            return (Some(p.fix(uid)), evs);
        }
        let (a, b) = ((p.x, p.z), (xm, zm));
        let (t_prev, was_anchored) = (p.at, p.anchored);
        p.x = xm;
        p.z = zm;
        p.y = y;
        p.yaw = (yaw.round() as i64).rem_euclid(360);
        p.v = v;
        p.dr = truthy(msg.get("dr"));
        if let (Some(q), None) = (q, p.q) {
            p.q0 = q;
            p.t0 = t;
        }
        p.q = q;
        p.at = t;
        p.anchored = true;
        if was_anchored {
            // Every gate this move passes, in order: only the next one counts.
            let last = stage.gates.len() - 1;
            while p.next <= last {
                let Some(f) = stage.gates[p.next].crossed(a, b) else { break };
                let ms = ms_since(go_at, t_prev + (t - t_prev) * f);
                p.splits.push(ms);
                if p.next == last {
                    p.fin = Some(ms);
                    evs.push(("finish", json!({"uid": uid, "ms": ms})));
                } else {
                    evs.push(("split", json!({"uid": uid, "gate": p.next, "ms": ms})));
                }
                p.next += 1;
            }
        }
        self.mark_dirty(uid);
        (None, evs)
    }

    /// Advance the stage clock; returns the events for the lobby, in order.
    pub fn tick(&mut self, t: f64, send: bool) -> Vec<(&'static str, Value)> {
        let mut evs = Vec::new();
        if self.phase == Phase::Countdown && t >= self.go_at {
            self.phase = Phase::Racing;
            for (_, p) in self.players.iter_mut() {
                p.at = t;
                p.bucket = (POS_BURST, t);
            }
        }
        if self.phase != Phase::Racing {
            return evs;
        }
        let over_time = t >= self.deadline();
        for (uid, p) in self.players.iter_mut() {
            if !p.racing() {
                continue;
            }
            if over_time {
                p.dnf = Some("timeout");
            } else if p.away.is_some_and(|a| t - a >= GRACE) {
                p.dnf = Some("disconnect");
            }
            if let Some(reason) = p.dnf {
                evs.push(("dnf", json!({"uid": uid, "reason": reason})));
            }
        }
        if !self.players.iter().any(|(_, p)| p.racing()) {
            evs.push(("done", self.finish_stage()));
            return evs;
        }
        if send && !self.dirty.is_empty() {
            let cars: Vec<Value> = self
                .players
                .iter()
                .filter(|(u, _)| self.dirty.contains(u))
                .map(|(uid, p)| {
                    let mut c = json!({"uid": uid, "x": (p.x * 100.0).round() as i64,
                                       "z": (p.z * 100.0).round() as i64, "y": (p.y * 100.0).round() as i64,
                                       "yaw": p.yaw, "v": p.v});
                    if p.dr {
                        c["dr"] = json!(1);
                    }
                    c
                })
                .collect();
            evs.push(("snap", json!({"t": wire_ms(t), "cars": cars})));
            self.dirty.clear();
        }
        evs
    }

    /// The stage is over: results (finishers by time, then the rest in grid
    /// order), the event's running totals, and the `done` payload.
    fn finish_stage(&mut self) -> Value {
        self.phase = Phase::Done;
        let mut order: Vec<usize> = (0..self.players.len()).collect();
        order.sort_by_key(|&i| (self.players[i].1.fin.is_none(), self.players[i].1.fin.unwrap_or(0)));
        let count = self.event_count();
        if let Some(e) = self.event.as_mut() {
            for (uid, p) in &self.players {
                let (sum, n) = e.totals.get(uid).copied().unwrap_or((0, 0));
                if let (Some(ms), true) = (p.fin, n == e.index) {
                    e.totals.insert(uid.clone(), (sum + ms, n + 1));
                }
            }
            e.completed = Some(e.index);
        }
        let results: Vec<Value> = order
            .iter()
            .enumerate()
            .map(|(i, &k)| {
                let (uid, p) = &self.players[k];
                let mut r = json!({"uid": uid, "name": name_of(&p.user), "ms": p.fin, "car": p.car,
                                   "place": i + 1, "dnf": p.fin.is_none(), "splits": p.splits});
                if let Some(e) = &self.event {
                    let total = e.totals.get(uid).filter(|(_, n)| *n == e.index + 1).map(|(s, _)| *s);
                    r["total"] = json!(total);
                }
                r
            })
            .collect();
        let mut done = json!({"results": results});
        if let Some(s) = &self.stage {
            done["key"] = json!(s.key);
            done["name"] = json!(s.name);
        }
        if let Some(e) = &self.event {
            done["event"] = json!({"index": e.index, "count": count});
        }
        self.results = Some(done.clone());
        done
    }

    /// A racer left. Mid-stage a dropped socket (blip) keeps their run for GRACE
    /// seconds; an explicit leave is a DNF at once. In the countdown they just go.
    /// Returns the dnf event to send, if any.
    pub fn drop_player(&mut self, uid: &str, t: f64, blip: bool) -> Option<Value> {
        let phase = self.phase;
        let p = self.player_mut(uid)?;
        if phase == Phase::Racing && p.racing() {
            if blip {
                p.away = Some(t);
                return None;
            }
            p.dnf = Some("left");
            return Some(json!({"uid": uid, "reason": "left"}));
        }
        if phase == Phase::Countdown {
            self.players.retain(|(u, _)| u != uid);
        }
        None
    }

    /// Back within the grace: the run carries on. Returns the fix that puts the
    /// reloaded page's car back where it was.
    pub fn restore(&mut self, uid: &str, pubv: Value, t: f64) -> Option<Value> {
        let p = self.player_mut(uid)?;
        if p.away.is_none() || !p.racing() {
            return None;
        }
        p.away = None;
        p.user = pubv;
        p.q = None; // a reloaded page starts a new clock
        p.at = t;
        p.bucket = (POS_BURST, t);
        Some(p.fix(uid))
    }
}

// -------------------------------------------------------------------- lobby --
/// One room's rally state: the lobby and the race.
#[derive(Debug, Default)]
pub struct RallyRoom {
    pub lobby: Lobby,
    pub rally: Rally,
}

impl RallyRoom {
    /// The `lobby` event: {players:[{uid,name,car,ready}], host, phase, stage?}.
    /// `ready` is whether that member is (or, between stages, will be) on the grid.
    pub fn lobby_ev(&self) -> Value {
        let r = &self.rally;
        let players: Vec<Value> = self
            .lobby
            .members
            .iter()
            .enumerate()
            .map(|(k, (uid, pubv))| {
                let car = r.player(uid).map(|p| p.car)
                    .or_else(|| r.cars.get(uid).copied())
                    .unwrap_or(k as i64 % CARS);
                let ready = if r.running() { r.player(uid).is_some_and(|p| p.dnf.is_none()) } else { k < MAX_PLAYERS };
                json!({"uid": uid, "name": name_of(pubv), "car": car, "ready": ready})
            })
            .collect();
        let mut v = json!({"players": players, "host": self.lobby.host, "phase": r.phase.as_str()});
        if let Some(s) = &r.stage {
            v["stage"] = json!({"key": s.key, "name": s.name, "gates": s.gates.len()});
        }
        v
    }
}

fn err(out: &mut Out, conn: u64, msg: &str) {
    out.push(To::Conn(conn), "error", json!({"msg": msg, "error": msg}));
}

/// The rally game for every room: lobby, referee and the per-room tick loop.
#[derive(Clone)]
pub struct RallyHub {
    inner: Arc<HubInner>,
}

struct HubInner {
    rooms: RoomManager,
    reg: Arc<Registry>,
    clock: Clock,
    /// Where a finished stage is written down. Empty in the unit tests.
    results: Recorder,
    state: Mutex<HashMap<String, RallyRoom>>,
}

fn tick_key(room_id: &str) -> String {
    format!("rally:{room_id}")
}

impl RallyHub {
    pub fn new(rooms: RoomManager, reg: Arc<Registry>, clock: Clock, results: Recorder) -> Self {
        Self { inner: Arc::new(HubInner { rooms, reg, clock, results, state: Mutex::new(HashMap::new()) }) }
    }

    pub fn now(&self) -> f64 {
        (self.inner.clock)()
    }

    pub fn registry(&self) -> &Arc<Registry> {
        &self.inner.reg
    }

    /// Look at (or change) a room's rally state, if it has any.
    pub fn with_room<R>(&self, room_id: &str, f: impl FnOnce(&mut RallyRoom) -> R) -> Option<R> {
        self.inner.state.lock().unwrap().get_mut(room_id).map(f)
    }

    /// A `{"type": "game", "g": "rally", ...}` message from one socket.
    pub async fn handle(&self, room_id: &str, conn: u64, member: &Member, msg: &Value) {
        let g = msg.get("g").and_then(Value::as_str);
        let op = msg.get("op").and_then(Value::as_str);
        let (Some(GAME), Some(op)) = (g, op) else {
            let mut out = Out::new(g.unwrap_or("?"));
            err(&mut out, conn, "unknown game");
            self.flush(room_id, out).await;
            return;
        };
        let mut out = Out::new(GAME);
        let mut invite: Option<String> = None;
        {
            let t = self.now();
            let uid = member.user_id.as_str();
            let mut st = self.inner.state.lock().unwrap();
            let v = st.entry(room_id.to_string()).or_default();
            match op {
                "join" => self.join(v, conn, member, &mut out, t),
                "leave" => leave_lobby(v, uid, &mut out, false, t),
                "invite" => {
                    let to = msg.get("uid").or_else(|| msg.get("to")).and_then(Value::as_str).unwrap_or("");
                    if !v.lobby.has(uid) {
                        err(&mut out, conn, "join the lobby first");
                    } else if to.is_empty() || to == uid {
                        err(&mut out, conn, "invite someone else");
                    } else {
                        invite = Some(to.to_string());
                    }
                }
                _ if !v.lobby.has(uid) => err(&mut out, conn, "join the lobby first"),
                _ => self.rally_op(room_id, v, conn, member, op, msg, &mut out, t),
            }
        }
        if let Some(to) = invite {
            let payload = json!({"type": "game", "g": GAME, "ev": "invite", "pv": crate::protocol::version(GAME),
                                 "from": member.public(), "room": room_id, "name": GAME_NAME});
            let delivered = self.inner.rooms.deliver_to_user(&to, payload.to_string()).await;
            out.push(To::Conn(conn), "invited", json!({"uid": to, "delivered": delivered}));
        }
        self.flush(room_id, out).await;
    }

    fn join(&self, v: &mut RallyRoom, conn: u64, member: &Member, out: &mut Out, t: f64) {
        let uid = member.user_id.as_str();
        let lobby = &mut v.lobby;
        if !lobby.has(uid) && lobby.members.len() >= MAX_LOBBY {
            err(out, conn, "this game's lobby is full");
            return;
        }
        lobby.blips.retain(|_, b| t - *b < HOST_GRACE);
        lobby.blips.remove(uid);
        match lobby.members.iter_mut().find(|(u, _)| u == uid) {
            Some(slot) => slot.1 = member.public(),
            None => lobby.members.push((uid.to_string(), member.public())),
        }
        let ph = lobby.prev_host.clone();
        let host_gone = lobby.host.as_deref().map(|h| !lobby.has(h)).unwrap_or(true);
        let host_back = ph.as_ref().map(|(h, at)| h == uid && t - at < HOST_GRACE).unwrap_or(false);
        if host_gone || host_back {
            lobby.host = Some(uid.to_string());
        }
        if ph.map(|(h, at)| h == uid || t - at >= HOST_GRACE).unwrap_or(false) {
            lobby.prev_host = None;
        }
        out.push(To::All, "lobby", v.lobby_ev());
        self.catch_up(v, conn, out);
        if let Some(fix) = v.rally.restore(uid, member.public(), t) {
            out.push(To::Conn(conn), "fix", fix);
        }
    }

    /// What a (re)joining or viewing socket needs: the stage, the green light
    /// if one is coming or has been, and the last results.
    fn catch_up(&self, v: &RallyRoom, conn: u64, out: &mut Out) {
        if let Some(r) = v.rally.rally_ev() {
            out.push(To::Conn(conn), "rally", r);
        }
        if v.rally.running() {
            out.push(To::Conn(conn), "go", v.rally.go_ev());
        } else if let (Phase::Done, Some(done)) = (v.rally.phase, &v.rally.results) {
            // To this socket only, so it is never recorded twice.
            out.push(To::Conn(conn), "done", done.clone());
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn rally_op(&self, room_id: &str, v: &mut RallyRoom, conn: u64, member: &Member, op: &str,
                msg: &Value, out: &mut Out, t: f64) {
        let uid = member.user_id.as_str();
        let ids = v.lobby.ids();
        match op {
            "pos" => {
                let (fix, evs) = v.rally.pos(uid, msg, t);
                if let Some(fix) = fix {
                    out.push(To::Conn(conn), "fix", fix);
                }
                let mut to = ids;
                for (u, _) in &v.rally.players {
                    if !to.contains(u) {
                        to.push(u.clone());
                    }
                }
                for (ev, data) in evs {
                    out.push(To::Users(to.clone(), None), ev, data);
                }
            }
            "view" => {
                out.push(To::Conn(conn), "lobby", v.lobby_ev());
                self.catch_up(v, conn, out);
            }
            "car" => match v.rally.car(uid, msg) {
                None => err(out, conn, "pick a car"),
                Some(c) => out.push(To::Users(ids, None), "car", json!({"uid": uid, "car": c})),
            },
            "start" | "end" => {
                if v.lobby.host.as_deref() != Some(uid) {
                    err(out, conn, "only the host can do that");
                    return;
                }
                v.lobby.prev_host = None;
                if op == "start" {
                    let null = Value::Null;
                    let stage = msg.get("stage").unwrap_or(&null);
                    let mut e = v.rally.start(&v.lobby.members, stage, msg.get("event"), t);
                    if e.is_none() && !self.tick_on(room_id) {
                        v.rally.end();
                        e = Some("the Arena is busy right now: try again in a minute".into());
                    }
                    match e {
                        Some(e) => err(out, conn, &e),
                        None => {
                            if let Some(r) = v.rally.rally_ev() {
                                out.push(To::Users(ids.clone(), None), "rally", r);
                            }
                            out.push(To::Users(ids.clone(), None), "go", v.rally.go_ev());
                            out.push(To::Users(ids, None), "lobby", v.lobby_ev());
                        }
                    }
                } else {
                    v.rally.end();
                    self.inner.reg.stop(&tick_key(room_id));
                    out.push(To::Users(ids, None), "lobby", v.lobby_ev());
                }
            }
            _ => err(out, conn, "unknown rally op"),
        }
    }

    /// Start the room's stage loop (a no-op if it runs). False: no slot under the budget.
    fn tick_on(&self, room_id: &str) -> bool {
        let hub = self.clone();
        let rid = room_id.to_string();
        let clock = self.inner.clock.clone();
        let step = move |t: f64, send: bool, tk: Arc<Ticker>| {
            let hub = hub.clone();
            let rid = rid.clone();
            async move { hub.step(&rid, t, send, &tk).await }
        };
        self.inner.reg.start(&tick_key(room_id), HZ, step, clock).is_some()
    }

    async fn step(&self, room_id: &str, t: f64, send: bool, tk: &Ticker) -> bool {
        if !self.inner.rooms.exists(room_id).await {
            return false;
        }
        let (out, ids, running) = {
            let mut st = self.inner.state.lock().unwrap();
            let Some(v) = st.get_mut(room_id) else { return false };
            if !v.rally.running() {
                return false;
            }
            let mut ids = v.lobby.ids();
            for (u, _) in &v.rally.players {
                if !v.lobby.has(u) {
                    ids.push(u.clone());
                }
            }
            let mut out = Out::new(GAME);
            for (ev, data) in v.rally.tick(t, send) {
                out.push(To::Users(ids.clone(), None), ev, data);
            }
            let running = v.rally.running();
            if !running {
                out.push(To::Users(ids.clone(), None), "lobby", v.lobby_ev());
            }
            (out, ids, running)
        };
        if !out.items.is_empty() {
            let n = self.inner.rooms.count_where(room_id, |m| ids.contains(&m.user_id)).await;
            let bytes: usize = out.items.iter().map(|(_, p)| p.to_string().len()).sum();
            tk.count(bytes * n.max(1));
            self.flush(room_id, out).await;
        }
        running
    }

    /// A socket went away: if that was the user's last socket in the room, leave
    /// the lobby as a dropped socket (blip). Call before `RoomManager::leave`.
    pub async fn on_disconnect(&self, room_id: &str, conn: u64, member: &Member) {
        if self.with_room(room_id, |_| ()).is_none() {
            return;
        }
        let uid = member.user_id.clone();
        if self.inner.rooms.other_conn(room_id, conn, |m| m.user_id == uid).await {
            return; // the same person is still here on another socket
        }
        let mut out = Out::new(GAME);
        let t = self.now();
        self.with_room(room_id, |v| leave_lobby(v, &uid, &mut out, true, t));
        self.flush(room_id, out).await;
        if !self.inner.rooms.other_conn(room_id, conn, |_| true).await {
            // Nobody else is in the room: forget its game and stop its loop.
            self.inner.state.lock().unwrap().remove(room_id);
            self.inner.reg.stop(&tick_key(room_id));
        }
    }

    async fn flush(&self, room_id: &str, out: Out) {
        let rooms = &self.inner.rooms;
        for (to, payload) in out.items {
            // A finished stage is written down from the server's own "done",
            // once, never from a client (as kart).
            if matches!(to, To::All | To::Users(..)) {
                if let Some(g) = crate::results::is_done(&payload) {
                    self.inner.results.record_later(g, &payload);
                }
            }
            let s = payload.to_string();
            match to {
                To::All => {
                    rooms.send_where(room_id, |_| true, s).await;
                }
                To::Conn(c) => {
                    rooms.send_conn(room_id, c, s).await;
                }
                To::Users(ids, skip) => {
                    rooms.send_where(room_id, |m| ids.contains(&m.user_id)
                                     && skip.as_deref() != Some(m.user_id.as_str()), s).await;
                }
            }
        }
    }
}

/// Leave the rally lobby. disconnected: the socket dropped rather than an
/// explicit leave, so the host is handed back on a quick return and the run
/// waits GRACE seconds before its DNF.
fn leave_lobby(v: &mut RallyRoom, uid: &str, out: &mut Out, disconnected: bool, t: f64) {
    let lobby = &mut v.lobby;
    let Some(i) = lobby.members.iter().position(|(u, _)| u == uid) else { return };
    lobby.members.remove(i);
    if disconnected {
        lobby.blips.insert(uid.to_string(), t);
    }
    if lobby.host.as_deref() == Some(uid) {
        lobby.host = lobby.members.first().map(|(u, _)| u.clone());
        lobby.prev_host = if disconnected && lobby.host.is_some() { Some((uid.to_string(), t)) } else { None };
    }
    let mut to = v.lobby.ids();
    for (u, _) in &v.rally.players {
        if !to.contains(u) && u != uid {
            to.push(u.clone());
        }
    }
    if let Some(d) = v.rally.drop_player(uid, t, disconnected) {
        out.push(To::Users(to.clone(), None), "dnf", d);
    }
    out.push(To::All, "lobby", v.lobby_ev());
}

