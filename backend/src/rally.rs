//! Valley Rally (g = "rally"): point-to-point stages through generated
//! countryside, up to 8 cars at once, timed gate by gate. Rust-only (HQ 2.7):
//! the frozen Python Arena never had it.
//!
//! Modelled on Kart Racing (`kart.rs`, whose header explains the design): each
//! player drives their own car in the browser and streams where it is; the
//! server runs a 15 Hz tick (`realtime.rs`) that sends the lobby one batched
//! snapshot per tick. The server does NOT simulate the cars. It checks that each
//! move is no faster than a car can go (and not a teleport), counts the stage's
//! gates in order, and times every split and the finish on its own clock.
//! Driving off the road is allowed: a rally car may cut across a field, and only
//! the gates say whether it went the right way.
//!
//! Stages are always user-made (generated by the client from a seed, or drawn):
//! the host starts one with `{"op":"start","stage":MapDoc}`. The MapDoc's `data`
//! goes through [`validate_custom`], which returns its CANONICAL form (rounded,
//! key order fixed, unknown keys dropped); the race is keyed by
//! `mapkey::content_key("rally", canonical)` ("c-" + 12 hex), so the same stage
//! always lands on the same leaderboard -- which is how the daily stage (seed
//! "daily-YYYY-MM-DD") gets exactly one board per day.
//!
//! Gates: a gate is a line across the road, centre (x, z), perpendicular to the
//! heading h (degrees, 0 = north = -z, 90 = east = +x), w metres either side of
//! the centre. It is crossed when the segment between two consecutive accepted
//! positions passes through that line in 2D, going forward (from behind the
//! line, against h, to on or past it). Only the NEXT gate counts: driving
//! through gate 3 before gate 2 does nothing. Crossing the last gate finishes.
//!
//! Start: the car's first accepted frame after "go" must be within
//! [`START_RADIUS`] of the road's first point; it anchors the car without
//! counting any gate. Gate 0 is a gate like any other and must be crossed.
//!
//! Units on the wire: x, z, y in centimetres, yaw in whole degrees, speed v in
//! decimetres/s, the sender's clock q in centiseconds; `at`, `t` and every `ms`
//! are server milliseconds (`ms` relative to `go.at`).
//!
//! Protocol: in `{"type":"game","g":"rally","op":...}`, out
//! `{"type":"game","g":"rally","ev":...}`. Ops: join, leave, invite, view, car,
//! start, end, pos. Events: lobby, rally, car, go, snap, split, finish, dnf,
//! done, fix, invite, invited, error.

